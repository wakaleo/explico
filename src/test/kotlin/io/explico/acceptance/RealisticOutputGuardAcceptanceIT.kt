/**
 * Acceptance tests for the output-directory guard (spec §14.80 step 1). `render --out DIR` used to delete DIR recursively, so `--out` set to a directory that held the policies (or
 * anything else) destroyed it (reproduced in the 1.0 API review). Authored from that review, NOT from the frozen acceptance-pack README. Decisions pinned here (operator decisions of
 * 2026-11-01; the exact texts are chosen here and /tdd must match them):
 *
 * - `RenderedDocs.writeTo(dir, force = false, protect = emptyList())` and `DiffReport.writeTo(file, force = false)` are the ONE guarded write; the CLI calls them.
 * - Every directory written holds a marker file `.explico-output` whose content is exactly `Generated by explico. This directory is replaced on every run.` + a newline (no version, no
 *   time). The marker is NOT in `RenderedDocs.files` (it would change every golden); `writeTo` adds it.
 * - A directory is replaced (deleted and recreated) only when it does not exist, is empty, or holds the marker. Any other non-empty directory is refused with an
 *   `OutputDirectoryException` (message contains `not empty` and `force`), nothing deleted, nothing written -- unless `force = true`.
 * - HARD refusals, even with `force = true`, decided by real path (symlinks and `..` resolved): a directory that IS or CONTAINS a `protect` directory or file (message contains `input`,
 *   and the check is independent of the marker), the user's home directory (the `user.home` property, read at call time) or one of its parents (`home directory`), a filesystem root
 *   (`filesystem root`). The current working directory and its parents are pinned by the process tests (a JVM cannot change its own).
 * - A path that is an existing file is refused (`not a directory`); `DiffReport.writeTo` refuses an existing directory even with force (`is a directory`), overwrites a regular file,
 *   creates parents, and writes no marker.
 * - `OutputDirectoryException.path` is the path as the caller gave it.
 *
 * Facade only. SAFETY: nothing here points at a real directory except the filesystem-root case, which is a guard-only call -- /tdd must implement the guard BEFORE any mutation.
 * Fixtures are the existing `realistic/group-by-control` policies (it has a `controls/` subdirectory) and `diff/diff-all-categories`.
 */
package io.explico.acceptance

import io.explico.DiffReport
import io.explico.Explico
import io.explico.OutputDirectoryException
import io.explico.RenderedDocs
import io.explico.opa.OpaRunner
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Assertions.assertThrows
import org.junit.jupiter.api.Assumptions.abort
import org.junit.jupiter.api.Assumptions.assumeTrue
import org.junit.jupiter.api.BeforeAll
import org.junit.jupiter.api.DisplayName
import org.junit.jupiter.api.Nested
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.nio.file.Files
import java.nio.file.Path

@DisplayName("Realistic policies: the output-directory guard")
class RealisticOutputGuardAcceptanceIT {

    companion object {
        private const val MARKER = ".explico-output"
        private const val MARKER_TEXT = "Generated by explico. This directory is replaced on every run.\n"
        private val policies = Path.of("src/test/resources/realistic/group-by-control/policies")
        private val diffBase = Path.of("src/test/resources/diff/diff-all-categories")

        private lateinit var docs: RenderedDocs
        private lateinit var report: DiffReport

        @JvmStatic
        @BeforeAll
        fun renderAll() {
            assumeTrue(OpaRunner.isAvailable(), "opa binary not on PATH")
            docs = Explico.render(Explico.load(policies), policies, groupByControl = true)
            report = Explico.diff(Explico.load(diffBase.resolve("old")), Explico.load(diffBase.resolve("new")))
        }

        /** Every file (relative path -> content) and directory (`name/` -> empty) under [dir], hidden ones included: a snapshot to compare before and after. */
        fun tree(dir: Path): Map<String, String> = if (!Files.exists(dir)) emptyMap() else Files.walk(dir).use { paths ->
            paths.filter { it != dir }.sorted().toList().associate { p ->
                val rel = dir.relativize(p).toString().replace('\\', '/')
                if (Files.isDirectory(p)) "$rel/" to "" else rel to Files.readString(p)
            }
        }

        /** What a successful write must leave: every rendered file, its parent directories, and the marker. */
        fun expectedTree(files: Map<String, String>): Map<String, String> {
            val expected = linkedMapOf<String, String>()
            for ((name, content) in files) {
                expected[name] = content
                var parent = name.substringBeforeLast('/', "")
                while (parent.isNotEmpty()) { expected["$parent/"] = ""; parent = parent.substringBeforeLast('/', "") }
            }
            expected[MARKER] = MARKER_TEXT
            return expected.toSortedMap()
        }

        /** A directory shaped like a user's project: the policies, the examples, the data and a notes file that must survive. */
        fun project(root: Path): Path {
            val project = root.resolve("project")
            copyTree(Path.of("src/test/resources/acceptance/policies"), project.resolve("policies"))
            copyTree(Path.of("src/test/resources/acceptance/examples"), project.resolve("examples"))
            copyTree(Path.of("src/test/resources/acceptance/data"), project.resolve("data"))
            Files.writeString(project.resolve("NOTES.txt"), "my notes\n")
            return project
        }

        private fun copyTree(from: Path, to: Path) {
            Files.walk(from).use { paths ->
                paths.forEach { p ->
                    val target = to.resolve(from.relativize(p).toString())
                    if (Files.isDirectory(p)) Files.createDirectories(target) else { Files.createDirectories(target.parent); Files.copy(p, target) }
                }
            }
        }

        /** Runs [write], which must be refused: the exception carries [dir], its message has every [reasons], and the tree under [watched] is exactly as it was. */
        fun assertRefused(dir: Path, watched: Path = dir, vararg reasons: String, write: () -> Unit) {
            val before = tree(watched)
            val e = assertThrows(OutputDirectoryException::class.java) { write() }
            assertThat(e.path).describedAs("the offending path as given").isEqualTo(dir)
            for (reason in reasons) assertThat(e.message).contains(reason)
            assertThat(tree(watched)).describedAs("nothing deleted, nothing written").isEqualTo(before)
        }
    }

    @Nested
    @DisplayName("Writing")
    inner class Writing {

        @Test
        @DisplayName("a directory that does not exist is created (with its parents) holding every file, the controls/ subdirectory and the marker")
        fun createsEverything(@TempDir tempDir: Path) {
            val dir = tempDir.resolve("a/b/out")

            docs.writeTo(dir)

            assertThat(docs.files.keys).anyMatch { it.startsWith("controls/") }
            assertThat(tree(dir)).isEqualTo(expectedTree(docs.files))
        }

        @Test
        @DisplayName("the marker is exactly one line, the pinned text, with no version and no time")
        fun markerText(@TempDir tempDir: Path) {
            docs.writeTo(tempDir.resolve("out"))

            assertThat(tempDir.resolve("out").resolve(MARKER)).exists()
            assertThat(Files.readString(tempDir.resolve("out").resolve(MARKER))).isEqualTo(MARKER_TEXT)
            assertThat(docs.files).doesNotContainKey(MARKER)
        }

        @Test
        @DisplayName("an existing empty directory is written into")
        fun emptyDirectory(@TempDir tempDir: Path) {
            val dir = Files.createDirectories(tempDir.resolve("out"))

            docs.writeTo(dir)

            assertThat(tree(dir)).isEqualTo(expectedTree(docs.files))
        }

        @Test
        @DisplayName("a directory that holds the marker is replaced entirely: stale files and subdirectories go, the marker stays")
        fun markedDirectoryIsReplaced(@TempDir tempDir: Path) {
            val dir = Files.createDirectories(tempDir.resolve("out/stale-subdir"))
            Files.writeString(dir.resolve("nested.md"), "leftover")
            Files.writeString(dir.parent.resolve("stale.md"), "leftover")
            Files.writeString(dir.parent.resolve(MARKER), "written by an older explico\n")

            docs.writeTo(dir.parent)

            assertThat(tree(dir.parent)).isEqualTo(expectedTree(docs.files))
        }

        @Test
        @DisplayName("two writes into two directories give byte-identical trees, and writing again over the first changes nothing")
        fun deterministic(@TempDir tempDir: Path) {
            docs.writeTo(tempDir.resolve("one"))
            docs.writeTo(tempDir.resolve("two"))
            docs.writeTo(tempDir.resolve("one"))

            assertThat(tree(tempDir.resolve("one"))).isEqualTo(expectedTree(docs.files))
            assertThat(tree(tempDir.resolve("one"))).isEqualTo(tree(tempDir.resolve("two")))
        }

        @Test
        @DisplayName("a path that is an existing file is refused (not a directory) and the file is untouched")
        fun existingFile(@TempDir tempDir: Path) {
            val file = tempDir.resolve("out")
            Files.writeString(file, "I am a file")

            assertRefused(file, tempDir, "not a directory") { docs.writeTo(file, force = true) }
        }
    }

    @Nested
    @DisplayName("A non-empty directory without the marker")
    inner class Unmarked {

        private fun unmarked(root: Path): Path {
            val dir = Files.createDirectories(root.resolve("out/inner"))
            Files.writeString(dir.resolve("keep.txt"), "my work")
            Files.writeString(dir.parent.resolve("NOTES.txt"), "my notes")
            return dir.parent
        }

        @Test
        @DisplayName("is refused, says it is not empty and that force exists, and every file keeps its bytes")
        fun refused(@TempDir tempDir: Path) {
            val dir = unmarked(tempDir)

            assertRefused(dir, dir, "not empty", "force") { docs.writeTo(dir) }
        }

        @Test
        @DisplayName("is replaced when force is true")
        fun forced(@TempDir tempDir: Path) {
            val dir = unmarked(tempDir)

            docs.writeTo(dir, force = true)

            assertThat(tree(dir)).isEqualTo(expectedTree(docs.files))
        }

        @Test
        @DisplayName("a directory next to the inputs is no problem: the guard does not over-refuse")
        fun neighbourIsFine(@TempDir tempDir: Path) {
            val project = project(tempDir)

            docs.writeTo(project.resolve("docs"), protect = listOf(project.resolve("policies")))

            assertThat(tree(project.resolve("docs"))).isEqualTo(expectedTree(docs.files))
            assertThat(Files.readString(project.resolve("NOTES.txt"))).isEqualTo("my notes\n")
        }
    }

    @Nested
    @DisplayName("Hard refusals: not even force overrides them")
    inner class Hard {

        @Test
        @DisplayName("a directory that contains the policies is refused (the reproduced bug): policies and notes survive")
        fun containsPolicies(@TempDir tempDir: Path) {
            val project = project(tempDir)

            assertRefused(project, project, "input") { docs.writeTo(project, force = true, protect = listOf(project.resolve("policies"))) }
        }

        @Test
        @DisplayName("likewise for the examples directory and for a data file")
        fun containsExamplesAndData(@TempDir tempDir: Path) {
            val project = project(tempDir)

            assertRefused(project, project, "input") { docs.writeTo(project, force = true, protect = listOf(project.resolve("examples"))) }
            assertRefused(project, project, "input") { docs.writeTo(project, force = true, protect = listOf(project.resolve("data/release/data.json"))) }
        }

        @Test
        @DisplayName("the policies directory itself is refused")
        fun isThePolicies(@TempDir tempDir: Path) {
            val policiesDir = project(tempDir).resolve("policies")

            assertRefused(policiesDir, policiesDir, "input") { docs.writeTo(policiesDir, force = true, protect = listOf(policiesDir)) }
        }

        @Test
        @DisplayName("the check is by real path: a `..` segment and a symlink do not get round it")
        fun byRealPath(@TempDir tempDir: Path) {
            val project = project(tempDir)
            Files.createDirectories(project.resolve("other"))
            val dotDot = project.resolve("other").resolve("..")
            assertRefused(dotDot, project, "input") { docs.writeTo(dotDot, force = true, protect = listOf(project.resolve("policies"))) }

            val link = tempDir.resolve("link")
            try { Files.createSymbolicLink(link, project) } catch (e: Exception) { abort("symbolic links are not available here: ${e.message}") }
            assertRefused(link, project, "input") { docs.writeTo(link, force = true, protect = listOf(project.resolve("policies"))) }

            val policiesLink = tempDir.resolve("policies-link")
            Files.createSymbolicLink(policiesLink, project.resolve("policies"))
            assertRefused(project, project, "input") { docs.writeTo(project, force = true, protect = listOf(policiesLink)) }
        }

        @Test
        @DisplayName("the protection does not depend on the marker: a marked directory that contains the policies is refused even without force")
        fun markedButContainsPolicies(@TempDir tempDir: Path) {
            val project = project(tempDir)
            Files.writeString(project.resolve(MARKER), MARKER_TEXT)

            assertRefused(project, project, "input") { docs.writeTo(project, protect = listOf(project.resolve("policies"))) }
        }

        @Test
        @DisplayName("the user's home directory and any parent of it are refused; a directory inside it is fine")
        fun home(@TempDir tempDir: Path) {
            val home = Files.createDirectories(tempDir.resolve("a/home"))
            Files.writeString(home.resolve("dotfile"), "mine")
            Files.writeString(home.parent.resolve("beside"), "mine too")
            val saved = System.getProperty("user.home")
            System.setProperty("user.home", home.toString())
            try {
                assertRefused(home, tempDir, "home directory") { docs.writeTo(home, force = true) }
                assertRefused(home.parent, tempDir, "home directory") { docs.writeTo(home.parent, force = true) }

                docs.writeTo(home.resolve("docs-out"))
                assertThat(tree(home.resolve("docs-out"))).isEqualTo(expectedTree(docs.files))
            } finally {
                System.setProperty("user.home", saved)
            }
        }

        @Test
        @DisplayName("a filesystem root is refused (a guard-only call: the check must run before anything is touched)")
        fun root() {
            val root = Path.of("").toAbsolutePath().root

            val e = assertThrows(OutputDirectoryException::class.java) { docs.writeTo(root, force = true) }

            assertThat(e.path).isEqualTo(root)
            assertThat(e.message).contains("filesystem root")
        }
    }

    @Nested
    @DisplayName("The change report is a file")
    inner class DiffFile {

        @Test
        @DisplayName("is written with its parent directories, exactly the report's Markdown, and no marker beside it")
        fun writes(@TempDir tempDir: Path) {
            val file = tempDir.resolve("reports/2026/change.md")

            report.writeTo(file)

            assertThat(report.markdown).isNotBlank()
            assertThat(file).exists()
            assertThat(Files.readString(file)).isEqualTo(report.markdown)
            assertThat(tree(tempDir.resolve("reports"))).containsOnlyKeys("2026/", "2026/change.md")
        }

        @Test
        @DisplayName("an existing regular file is overwritten, with or without force")
        fun overwrites(@TempDir tempDir: Path) {
            val file = tempDir.resolve("change.md")
            Files.writeString(file, "an older report")
            report.writeTo(file)
            assertThat(Files.readString(file)).isEqualTo(report.markdown)

            Files.writeString(file, "an older report")
            report.writeTo(file, force = true)
            assertThat(Files.readString(file)).isEqualTo(report.markdown)
        }

        @Test
        @DisplayName("an existing directory is refused (is a directory), even with force, and nothing in it is touched")
        fun directoryRefused(@TempDir tempDir: Path) {
            val dir = Files.createDirectories(tempDir.resolve("change.md"))
            Files.writeString(dir.resolve("mine.txt"), "mine")

            assertRefused(dir, dir, "is a directory") { report.writeTo(dir) }
            assertRefused(dir, dir, "is a directory") { report.writeTo(dir, force = true) }
        }
    }
}
