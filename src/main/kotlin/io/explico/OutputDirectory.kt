package io.explico

import java.nio.file.Files
import java.nio.file.Path
import java.util.Comparator

/**
 * The decisions about where explico may write (spec §14.80 step 1). Pure: it looks at the file system and never changes it, so every check runs BEFORE anything is deleted.
 *
 * Paths are compared by REAL path -- the longest existing prefix is resolved through symlinks and `..`, the rest (not created yet) is appended and normalised -- so neither a
 * `..` segment nor a symlink gets round a refusal. Every refusal is one line naming the path as the caller gave it.
 */
internal object OutputGuard {
    /** The file that marks a directory as generated by explico (and so safe to replace). */
    const val MARKER = ".explico-output"

    /** Its exact content: one line, no version, no time. */
    const val MARKER_TEXT = "Generated by explico. This directory is replaced on every run.\n"

    /** The user's home directory (the `user.home` property, read at call time), or null when unknown. */
    fun homeDirectory(): Path? = System.getProperty("user.home")?.takeIf { it.isNotBlank() }?.let { Path.of(it) }

    /**
     * Decides whether [dir] may be deleted and recreated, and returns the REAL path to write to. Refused whatever [force] says: a filesystem root, the [home] directory or a parent
     * of it, the [cwd] or a parent of it, a directory that is or contains one of the [protect]ed inputs, and an existing file. Refused unless [force]: a non-empty directory without
     * the [MARKER].
     */
    fun checkDirectory(
        dir: Path,
        force: Boolean,
        protect: List<Path> = emptyList(),
        home: Path? = homeDirectory(),
        cwd: Path = Path.of("").toAbsolutePath(),
    ): Path {
        if (Files.isSymbolicLink(dir) && !Files.exists(dir)) throw refuse(dir, "it is a symbolic link that points nowhere")
        val real = realPath(dir)
        if (real.parent == null) throw refuse(dir, "it is a filesystem root")
        if (home != null && realPath(home).startsWith(real)) throw refuse(dir, "it is, or contains, your home directory")
        if (realPath(cwd).startsWith(real)) throw refuse(dir, "it is, or contains, the working directory")
        for (input in protect) {
            if (realPath(input).startsWith(real)) throw refuse(dir, "it is, or contains, an input ($input) that would be deleted")
        }
        if (Files.exists(real)) {
            if (!Files.isDirectory(real)) throw refuse(dir, "it is not a directory")
            if (!force && !hasMarker(real) && isNotEmpty(real)) {
                throw refuse(dir, "it is not empty and was not generated by explico (pass --force, or force = true, to replace it)")
            }
        }
        return real
    }

    /** Decides whether [file] may be written: an existing directory never may (that is `--out` pointing at a directory), whatever `force` says. */
    fun checkFile(file: Path) {
        if (Files.isDirectory(file)) throw OutputDirectoryException(file, "refusing to write the report to $file: it is a directory")
    }

    /** The marker proves explico wrote the directory only if it is a regular file itself, not a link to some other file or a directory (security review L3). */
    private fun hasMarker(dir: Path): Boolean = Files.isRegularFile(dir.resolve(MARKER), java.nio.file.LinkOption.NOFOLLOW_LINKS)

    private fun refuse(dir: Path, reason: String) = OutputDirectoryException(dir, "refusing to write to $dir: $reason")

    private fun isNotEmpty(dir: Path): Boolean = Files.list(dir).use { it.findFirst().isPresent }

    private fun realPath(path: Path): Path {
        val absolute = path.toAbsolutePath()
        var existing: Path = absolute
        while (!Files.exists(existing)) existing = existing.parent ?: break
        val base = if (Files.exists(existing)) existing.toRealPath() else absolute.root
        return base.resolve(existing.relativize(absolute).toString()).normalize()
    }
}

/** The ONE place explico deletes or writes its output (spec §14.80 step 1); every write is checked by [OutputGuard] first. */
internal object OutputWriter {
    /**
     * Replaces [dir] with [files]: guard, then delete and recreate it, write the marker first (so an interrupted run leaves a directory the next run may replace), then every file in
     * name order, creating subdirectories.
     */
    fun writeDirectory(dir: Path, files: Map<String, String>, force: Boolean, protect: List<Path>) {
        val target = OutputGuard.checkDirectory(dir, force, protect)
        if (Files.exists(target)) Files.walk(target).use { paths -> paths.sorted(Comparator.reverseOrder()).forEach(Files::delete) }
        Files.createDirectories(target)
        Files.writeString(target.resolve(OutputGuard.MARKER), OutputGuard.MARKER_TEXT)
        for ((name, content) in files.toSortedMap()) {
            val file = target.resolve(name)
            Files.createDirectories(file.parent)
            Files.writeString(file, content)
        }
    }

    /** Writes [text] to [file], creating its parents and replacing a regular file; an existing directory is refused. */
    fun writeFile(file: Path, text: String) {
        OutputGuard.checkFile(file)
        file.toAbsolutePath().parent?.let { Files.createDirectories(it) }
        Files.writeString(file, text)
    }
}
