/**
 * Spec §14.81: companion Rego rules that say WHICH situation of a rendered rule applied, for an application that evaluates the policy itself (for example compiled to
 * WebAssembly) and cannot ask explico or `opa` at that point.
 */
package io.explico.generate

import io.explico.model.Condition
import io.explico.model.PolicyPackage
import io.explico.model.PolicySet
import io.explico.model.RuleGroup
import io.explico.opa.OpaExpr
import io.explico.opa.OpaModule
import io.explico.opa.OpaRule
import io.explico.opa.OpaRunner
import java.util.Base64

internal object SituationCompanion {

    /** First line of every generated file. `Explico.load` and the policy digest skip a `.rego` file that starts with it, so generated files never become policy input. */
    const val MARKER = "# Generated by explico"

    /** True for the text of a `.rego` file explico generated. */
    fun isGenerated(text: String): Boolean = text.startsWith(MARKER)

    /** True when the file at [path] is one explico generated (its first line is the [MARKER]). */
    fun isGeneratedFile(path: java.nio.file.Path): Boolean = try {
        java.nio.file.Files.newInputStream(path).use { it.readNBytes(MARKER.length) }.toString(Charsets.UTF_8) == MARKER
    } catch (e: java.io.IOException) {
        false
    }

    /** Where the companion file for the policy file [sourceFile] is written, relative to the output directory. */
    fun outputPath(sourceFile: String): String = "situations/$sourceFile"

    private sealed interface Outcome {
        data class Rule(val text: String) : Outcome
        data class Skipped(val reason: String) : Outcome
    }

    /**
     * One generated file per policy file that holds a rule worth a companion (or a rule that had to be skipped, which the file says): `situations/<policy file>`.
     * Each is the SAME package with the SAME `import` lines as the file it came from, so it compiles with the original and sees the same helpers. The rule bodies are
     * copied statement by statement from opa's own source locations -- nothing is re-derived. Numbers are the card's situation numbers.
     */
    fun generate(policySet: PolicySet): Map<String, String> {
        val dir = requireNotNull(policySet.sourceDir) { "emit situations needs the policy set's sourceDir" }
        val result = linkedMapOf<String, String>()
        for (pkg in policySet.packages) {
            for (file in pkg.sourceFiles.sorted()) {
                val module = OpaRunner.parse(dir.resolve(file), policySet.regoVersion)
                val body = StringBuilder()
                for (group in pkg.rules.sortedBy { it.bodies.firstOrNull()?.sourceLocation?.row ?: 0 }) {
                    val first = group.bodies.firstOrNull() ?: continue
                    if (first.sourceLocation.file != file || group.isSplitDefaultEntry) continue
                    when (val outcome = companionFor(pkg, group, module, file)) {
                        is Outcome.Rule -> body.appendLine(outcome.text).appendLine()
                        is Outcome.Skipped -> body.appendLine("# No companion rule for `${group.name}`: ${outcome.reason}.").appendLine()
                    }
                }
                if (body.isEmpty()) continue
                val header = StringBuilder()
                header.appendLine("$MARKER from `${pkg.path}` ($file). Do not edit.")
                header.appendLine("# Each rule here says which situation of the rule it is named after applied, using the situation numbers of its documentation card.")
                header.appendLine()
                header.appendLine("package ${pkg.path}")
                header.appendLine()
                module.imports.forEach { import ->
                    val path = sourceOf(import.path.location) ?: error("opa gave no source text for an import")
                    header.appendLine("import $path" + (import.alias?.let { " as $it" } ?: ""))
                }
                if (module.imports.isNotEmpty()) header.appendLine()
                result[outputPath(file)] = header.toString() + body.toString().trimEnd() + "\n"
            }
        }
        return result
    }

    private fun companionFor(pkg: PolicyPackage, group: RuleGroup, module: OpaModule, file: String): Outcome {
        // A function has no partial form (Rego cannot OR several definitions of one function into a set), and several definitions that both apply are a conflict, so only
        // a function with one definition (or one `else` chain) is numbered.
        if (group.parameters.isNotEmpty() && group.bodies.size > 1) {
            return Outcome.Skipped("it is a function with several definitions, and a function cannot report several situations")
        }
        if (pkg.rules.count { it.name == group.name && !it.isSplitDefaultEntry } > 1) {
            return Outcome.Skipped("its name is used by several cards, whose situation numbers would clash")
        }
        if (group.bodies.any { body -> body.conditions.singleOrNull().let { it is Condition.Unrendered && it.reason in WHOLLY_AS_SOURCE } }) {
            return Outcome.Skipped("explico shows it entirely as source, so it has no situations to number")
        }
        if (group.bodies.any { it.sourceLocation.file != file }) return Outcome.Skipped("its definitions are in several files")
        val situation = "${group.name}__situation"
        val situations = "${group.name}__situations"
        if (pkg.rules.any { it.name == situation || it.name == situations }) return Outcome.Skipped("a rule named `$situation` or `$situations` already exists")

        val rules = group.bodies.map { body ->
            module.rules.firstOrNull { it.location?.row == body.sourceLocation.row && !it.default } ?: return Outcome.Skipped("its source could not be found again")
        }
        val partial = rules.first().head.key != null
        // The companion of a function takes the same arguments, written as the function writes them (a pattern argument stays a pattern).
        val arguments = rules.first().head.args?.let { args -> "(" + args.joinToString(", ") { sourceOf(it.location) ?: error("opa gave no source text for an argument") } + ")" } ?: ""
        val chain = group.bodies.size == 1 && group.bodies.single().elseBranches.isNotEmpty()
        val text = StringBuilder()
        if (chain) {
            val branches = generateSequence(rules.single()) { it.elseBranch }.toList()
            if (branches.size != 1 + group.bodies.single().elseBranches.size) return Outcome.Skipped("its source could not be matched to the card")
            branches.forEachIndexed { index, branch ->
                text.append(if (index == 0) "$situation$arguments := ${index + 1}" else " else := ${index + 1}")
                if (!hasNoStatements(branch)) text.append(" if {\n").append(statementsOf(branch)).append("}")
            }
        } else if (rules.size == 1 && !partial) {
            text.append("$situation$arguments := 1")
            if (!hasNoStatements(rules.single())) text.append(" if {\n").append(statementsOf(rules.single())).append("}")
        } else {
            rules.forEachIndexed { index, rule ->
                if (index > 0) text.append("\n")
                text.append("$situations contains ${index + 1}")
                if (!hasNoStatements(rule)) text.append(" if {\n").append(statementsOf(rule)).append("}")
            }
        }
        return Outcome.Rule(text.toString())
    }

    /**
     * True when [rule] has no statements of its own: opa gives a body-less rule (or a body-less `else`) one synthetic `true` statement. An explicit `if { true }` reads
     * the same, and is worded the same way (no statements), which is equivalent.
     */
    private fun hasNoStatements(rule: OpaRule): Boolean {
        val only = rule.body.singleOrNull() ?: return rule.body.isEmpty()
        val terms = only.terms as? kotlinx.serialization.json.JsonObject ?: return false
        return terms["type"]?.toString() == "\"boolean\"" && terms["value"]?.toString() == "true"
    }

    /** Condition fallbacks that stand for a whole rule rather than one statement: the card has no numbered situations for them. */
    private val WHOLLY_AS_SOURCE = setOf("else-chain", "mapping-error")

    /** The statements of [rule]'s body, each exactly as written (opa's own text for it), one per line, indented. */
    private fun statementsOf(rule: OpaRule): String =
        rule.body.joinToString("") { expr -> "    ${sourceOf(expr)}\n" }

    private fun sourceOf(expr: OpaExpr): String = sourceOf(expr.location) ?: error("opa gave no source text for a statement")

    private fun sourceOf(location: io.explico.opa.OpaLocation?): String? =
        location?.text?.let { String(Base64.getDecoder().decode(it), Charsets.UTF_8) }
}
